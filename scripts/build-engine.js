// Run: npm run build:engine [-- --native]
// Compiles engine/stowage.cpp to WebAssembly with clang (needs the wasm32 target and wasm-ld:
// `sudo apt install clang lld`) and embeds it as base64 in js/engine-wasm.js, which is committed
// so the app runs without a compiler. --native also builds the command-line engine in build/.
const { execFileSync } = require('child_process');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const out = path.join(root, 'build');
fs.mkdirSync(out, { recursive: true });
const src = f => path.join(root, 'engine', f);
// -ffp-contract=off: no fused multiply-add, so every result rounds exactly like JavaScript
const common = ['-O3', '-ffp-contract=off', '-fno-exceptions', '-fno-rtti', '-Wall', '-Wextra'];
const cxx = process.env.CXX_WASM || 'clang++';

const wasmFile = path.join(out, 'stowage.wasm');
execFileSync(cxx, ['--target=wasm32', '-nostdlib', ...common,
    '-Wl,--no-entry', '-Wl,--export=stow_input', '-Wl,--export=stow_run', '-Wl,-z,stack-size=1048576',
    src('stowage.cpp'), src('wasm_main.cpp'), '-o', wasmFile], { stdio: 'inherit' });
const b64 = fs.readFileSync(wasmFile).toString('base64');
fs.writeFileSync(path.join(root, 'js', 'engine-wasm.js'),
    '// Generated by `npm run build:engine` from engine/*.cpp — do not edit.\n' +
    `(typeof window !== 'undefined' ? window : globalThis).STOWAGE_WASM_B64 = '${b64}';\n`);
console.log(`js/engine-wasm.js (${fs.statSync(wasmFile).size} bytes wasm)`);

if (process.argv.includes('--native')) {
    const exe = path.join(out, process.platform === 'win32' ? 'stowage.exe' : 'stowage');
    execFileSync(process.env.CXX || 'clang++', ['-std=c++17', ...common, src('stowage.cpp'), src('native_cli.cpp'), '-o', exe], { stdio: 'inherit' });
    console.log(path.relative(root, exe));
}
